import * as vscode from "vscode";
import * as fs from "fs/promises";
import * as path from "path";
import { resolveCli, type ResolvedCli } from "./cli";

/**
 * A stable launcher for the MCP server.
 *
 * The analyzer lives inside the extension directory, whose name carries the
 * version (`clarifydoc.clarifydoc-vscode-0.1.0`), so any agent config that
 * pointed straight at it would break on the next extension update — silently,
 * as a spawn failure inside someone else's tool. This writes a tiny script to a
 * path that never changes:
 *
 *   <globalStorage>/bin/clarifydoc-mcp        (clarifydoc-mcp.cmd on Windows)
 *
 * It is rewritten on every activation, so it always points at the currently
 * installed bundle and the currently resolved Node runtime — including VS
 * Code's own Electron-as-Node, which is why an agent needs no Node install of
 * its own.
 */

export function shimPath(context: vscode.ExtensionContext): string {
  const name = process.platform === "win32" ? "clarifydoc-mcp.cmd" : "clarifydoc-mcp";
  return path.join(context.globalStorageUri.fsPath, "bin", name);
}

/**
 * The same launcher without the `mcp` subcommand — `clarifydoc hook …`,
 * `clarifydoc install …` — for what an agent host runs besides the server
 * (Claude Code hooks). Written beside it, refreshed with it.
 */
export function cliShimPath(context: vscode.ExtensionContext): string {
  const name = process.platform === "win32" ? "clarifydoc.cmd" : "clarifydoc";
  return path.join(context.globalStorageUri.fsPath, "bin", name);
}

/** Quote a path for POSIX sh (single-quoted, with embedded quotes escaped). */
function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function posixShim(cli: ResolvedCli, version: string, sub: string | null = "mcp"): string {
  const target = [cli.command, ...cli.baseArgs].map(shQuote).join(" ");
  return [
    "#!/bin/sh",
    `# ClarifyDoc MCP server — generated by the ClarifyDoc VS Code extension v${version}.`,
    "# Rewritten on every activation; do not edit. Point your agent at THIS path",
    "# and an extension update cannot break it.",
    "#",
    "# Args are forwarded, so `clarifydoc-mcp` serves the project in the current",
    "# directory and `clarifydoc-mcp /path/to/project` serves that one.",
    cli.electronAsNode ? "export ELECTRON_RUN_AS_NODE=1" : "",
    `exec ${target}${sub ? ` ${sub}` : ""} "$@"`,
    "",
  ]
    .filter((line) => line !== "")
    .join("\n");
}

function windowsShim(cli: ResolvedCli, version: string, sub: string | null = "mcp"): string {
  const target = [cli.command, ...cli.baseArgs].map((p) => `"${p}"`).join(" ");
  return [
    "@echo off",
    `rem ClarifyDoc MCP server — generated by the ClarifyDoc VS Code extension v${version}.`,
    "rem Rewritten on every activation; do not edit. Point your agent at THIS path",
    "rem and an extension update cannot break it.",
    "setlocal",
    cli.electronAsNode ? 'set "ELECTRON_RUN_AS_NODE=1"' : "",
    `${target}${sub ? ` ${sub}` : ""} %*`,
    "",
  ]
    .filter((line) => line !== "")
    .join("\r\n");
}

/**
 * Write (or refresh) the launcher. Returns its path, or undefined when it could
 * not be written — the in-editor MCP server does not need it, so a failure here
 * only costs external agents the one-line config.
 */
export async function writeMcpShim(
  context: vscode.ExtensionContext,
  output: vscode.LogOutputChannel,
): Promise<string | undefined> {
  const target = shimPath(context);
  const cli = await resolveCli(context.extensionPath);
  const version = String(context.extension?.packageJSON?.version ?? "0.1.0");
  const body = process.platform === "win32" ? windowsShim(cli, version) : posixShim(cli, version);
  // The general launcher too, for hooks; its failure costs only those.
  const general = process.platform === "win32" ? windowsShim(cli, version, null) : posixShim(cli, version, null);
  await fs.mkdir(path.dirname(target), { recursive: true }).catch(() => undefined);
  await fs.writeFile(cliShimPath(context), general, "utf-8").then(() => (process.platform !== "win32" ? fs.chmod(cliShimPath(context), 0o755) : undefined)).catch(() => undefined);

  try {
    await fs.mkdir(path.dirname(target), { recursive: true });
    const existing = await fs.readFile(target, "utf-8").catch(() => null);
    if (existing !== body) {
      await fs.writeFile(target, body, "utf-8");
      output.info(`[mcp] wrote launcher ${target} → ${cli.display}`);
    }
    if (process.platform !== "win32") await fs.chmod(target, 0o755);
    return target;
  } catch (err) {
    output.warn(`[mcp] could not write launcher ${target}: ${(err as Error).message}`);
    return undefined;
  }
}
